# Regenerate util/efpga-requirements.txt, the hash-locked Python layer of the
# eFPGA shell (`nix develop .#efpga`; needs only `uv`).
# Nothing is resolved: the versions and hashes are FABulous 2.2.0's own uv.lock,
# which its PyPI wheel carries in fabulous_nix/. Same wheel in, same file out.
# A version bump changes the two pin lines below and FABULOUS in
# util/mosaic_gen/efpga_gen.py (test_efpga_fabric.py checks they agree).
set -euo pipefail
out="${1:?usage: efpga-lock.sh <output requirements file>}"
fab="fabulous-fpga==2.2.0 --hash=sha256:a35949a26868d1be94f0fb70a2e30fc90a5f310ecaf4bba977fa2d84b5f4aadf"
# Upstream locks sdf-timing to a git commit of its fork, which --require-hashes
# cannot verify. The PyPI release satisfies FABulous's unpinned `sdf-timing`;
# it lacks the fork's SDF lexer fix, which only the timing-model flow reads.
sdf="sdf-timing==0.0.post131 --hash=sha256:659a1f3a9b9d99a542169816d158d16bbb09de8a5b9a7289e3ca8b844be91d9b"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
echo "$fab" > "$tmp/fab.txt"
uv pip install --quiet --no-deps --require-hashes --target "$tmp/x" -r "$tmp/fab.txt"
{
  echo "# Copyright 2026 MOSAIC-SoC contributors"
  echo "# SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1"
  echo "# GENERATED by util/efpga-lock.sh from FABulous-FPGA 2.2.0's uv.lock. Do not edit."
  uv export --project "$tmp/x/fabulous_nix" --frozen --no-dev --no-emit-project \
    --no-emit-package sdf-timing --no-header --no-annotate --format requirements-txt
  echo "$fab"
  echo "$sdf"
} > "$tmp/requirements.txt"
mv "$tmp/requirements.txt" "$out"  # only a complete file replaces the lock
